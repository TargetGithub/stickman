// Reports over the specs: coverage against the allocation, aggregated needs, band indexes and shard briefs.
import { BANDS, splitId } from "./load.mjs";
import { FEATURE_ALIASES, impliedFeatures } from "./rules.mjs";
import { bandTables } from "./alloc.mjs";

const esc = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");

/**
 * Counts per band and row against the allocation.
 * @param {object} p  programme
 * @param {object[]} specs  parsed specs
 */
export function coverage(p, specs) {
  const bands = {};
  const stray = [];
  const byRow = new Map();
  for (const s of specs) {
    const row = p.slotIndex.get(s.id);
    const legacy = (splitId(s.id)?.slot ?? 0) <= 100;
    if (!row) { if (!legacy) stray.push(s.id); continue; }
    if (!byRow.has(row)) byRow.set(row, []);
    byRow.get(row).push(s.id);
  }
  let target = 0, written = 0;
  for (const b of BANDS) {
    const rows = (p.allocation[b].rows ?? []).map((r) => ({ key: r.key, slots: r.slots, subject: r.subject, strand: r.strand, target: r.count, ids: byRow.get(r) ?? [] }));
    const w = rows.reduce((a, r) => a + r.ids.length, 0);
    bands[b] = { target: p.bands.bands[b].total, allocated: rows.reduce((a, r) => a + r.target, 0), written: w, rows };
    target += bands[b].target;
    written += w;
  }
  return { target, written, bands, stray };
}

export function coverageMd(c, p) {
  const out = ["# 10K coverage", "", "<!-- Generated by engine3d/tools/spec10k.mjs coverage. Do not edit. -->", "",
    `${c.written} of ${c.target} specs written (${pct(c.written, c.target)}).`, "",
    "| Band | Target | Rows allocated | Written | Done |", "|---|---|---|---|---|"];
  for (const b of BANDS) { const x = c.bands[b]; out.push(`| ${b} ${p.bands.bands[b].name} | ${x.target} | ${x.allocated} | ${x.written} | ${pct(x.written, x.target)} |`); }
  if (c.stray.length) out.push("", `**Specs outside every slot range:** ${c.stray.join(", ")}`);
  for (const b of BANDS) {
    const x = c.bands[b];
    if (!x.rows.length) continue;
    out.push("", `## ${b}`, "", "| Row | Slots | Target | Written | Missing |", "|---|---|---|---|---|");
    for (const r of x.rows) out.push(`| ${r.key} | ${r.slots ?? "–"} | ${r.target} | ${r.ids.length} | ${r.target - r.ids.length} |`);
  }
  return `${out.join("\n")}\n`;
}

const pct = (a, b) => `${b ? Math.round((1000 * a) / b) / 10 : 0}%`;

/**
 * Aggregate needs: new assets/features (with how many specs need each) and usage of existing names.
 * @param {object[]} specs
 */
export function aggregateNeeds(specs) {
  const groups = ["characters", "props", "stages", "features"];
  const fresh = Object.fromEntries(groups.map((g) => [g, new Map()]));
  const used = Object.fromEntries(groups.map((g) => [g, new Map()]));
  const add = (m, name, id, desc) => {
    if (!m.has(name)) m.set(name, { name, count: 0, ids: [], descriptions: [] });
    const x = m.get(name);
    if (x.ids.includes(id)) return;
    x.count++;
    x.ids.push(id);
    if (desc && !x.descriptions.includes(desc)) x.descriptions.push(desc);
  };
  for (const s of specs) {
    for (const g of groups) {
      for (const n of s.needs?.[g] ?? []) {
        if (typeof n === "string") add(used[g], g === "features" ? FEATURE_ALIASES[n] ?? n : n, s.id);
        else add(fresh[g], n.name.slice(4), s.id, n.description);
      }
    }
    for (const f of impliedFeatures(s)) add(used.features, f, s.id);
    if (s.magical_moment?.id?.startsWith("new:")) add(fresh.features, `magic_${s.magical_moment.id.slice(4)}`, s.id, s.magical_moment.description);
  }
  const sort = (m) => [...m.values()].sort((a, b) => b.count - a.count || (a.name < b.name ? -1 : 1));
  return { new: Object.fromEntries(groups.map((g) => [g, sort(fresh[g])])), existing: Object.fromEntries(groups.map((g) => [g, sort(used[g])])) };
}

export function needsMd(n, specCount) {
  const out = ["# 10K needs: assets and engine features the specs ask for", "", "<!-- Generated by engine3d/tools/spec10k.mjs needs. Do not edit. -->", "",
    `From ${specCount} specs. "New" entries are what the asset and engine waves build; the count is how many specs need each one.`];
  for (const g of Object.keys(n.new)) {
    out.push("", `## New ${g} (${n.new[g].length})`, "");
    if (!n.new[g].length) { out.push("None."); continue; }
    out.push("| Name | Specs | Description(s) | First specs |", "|---|---|---|---|");
    for (const x of n.new[g]) out.push(`| \`${x.name}\` | ${x.count} | ${esc(x.descriptions.slice(0, 3).join(" / "))} | ${x.ids.slice(0, 6).join(", ")}${x.ids.length > 6 ? " …" : ""} |`);
  }
  out.push("", "## Existing names in use", "");
  for (const g of Object.keys(n.existing)) out.push(`- **${g}:** ${n.existing[g].map((x) => `${x.name} (${x.count})`).join(", ") || "–"}`);
  return `${out.join("\n")}\n`;
}

/** Markdown index for one band. */
export function bandIndexMd(p, b, specs) {
  const band = p.bands.bands[b];
  const list = specs.filter((s) => s.band === b).sort((x, y) => (x.id < y.id ? -1 : 1));
  const out = [`# ${b} · ${band.name}: spec index`, "", "<!-- Generated by engine3d/tools/spec10k.mjs index. Do not edit. -->", "",
    `${list.length} of ${band.total} specs.`, "", "| Id | Title | Subject · strand | Standard | Series | Length | Objective | Status |", "|---|---|---|---|---|---|---|---|"];
  for (const s of list) out.push(`| [${s.id}](${s.id}.json) | ${esc(s.title)} | ${s.subject} · ${s.strand} | ${esc(s.standards.join(", "))} | ${s.series} | ${Math.floor(s.target_length_s / 60)}:${String(s.target_length_s % 60).padStart(2, "0")} | ${esc(s.objective)} | ${s.status} |`);
  return `${out.join("\n")}\n`;
}

/**
 * The shard brief for one band: the band's slots and standards, the series it may use, and the common rules.
 * @param {object} p
 * @param {string} b
 * @param {string} common  shards/_COMMON.md
 * @param {object[]} existing  loadExisting() records
 */
export function shardBriefMd(p, b, common, existing) {
  const band = p.bands.bands[b];
  const rows = p.allocation[b].rows ?? [];
  const first = rows[0]?.slots?.slice(0, 4), last = rows[rows.length - 1]?.slots?.slice(5);
  const series = Object.entries(p.series.series).filter(([, s]) => s.bands.includes(b));
  const owned = series.filter(([, s]) => s.bands.length === 1 || s.bands[0] === b);
  const prefix = { bb: ["bb", "br"], pk: ["pk"], kg: ["kg"], g1: ["g1"], g2: ["g2"], g3: ["g3"], g4: ["g4"], g5: ["g5"] }[b];
  const ex = existing.filter((e) => prefix.some((x) => e.id.startsWith(x)) && !e.id.includes("~"));
  const out = [`# Shard brief: ${b} · ${band.name} (ages ${band.ages})`, "", "<!-- Generated by engine3d/tools/spec10k.mjs shards from allocation/*.json and shards/_COMMON.md. Do not edit; edit those. -->", "",
    `**You write ${band.total} specs: ids ${b}${first ?? "????"} to ${b}${last ?? "????"}, files \`10K/specs/${b}/<id>.json\`.** Only ids inside the slot ranges below; never another band's.`, "",
    `- Audience \`${band.audience}\`; length ${band.lengthS[0]}-${band.lengthS[1]} s; host ${band.host}; sidekick ${band.sidekick}.`,
    `- Voice: ${band.voice}. Music: ${band.music}.`, `- Framework: ${band.framework}.`, "",
    "## Series you may use", "", "| Series | Owned here | Subjects | Format | Mechanics | Tracker | Magic pool |", "|---|---|---|---|---|---|---|"];
  for (const [k, s] of series) out.push(`| \`${k}\` ${s.name} | ${owned.some(([o]) => o === k) ? "yes" : `shared (${s.bands.join(", ")})`} | ${s.subjects.join(", ")} | ${esc(s.format)} | ${s.mechanics.join(", ")} | ${esc(s.tracker)} | ${s.magic.join(", ")} |`);
  out.push("", "A shared series is used by several bands; keep its format but pitch the objective, the language and the difficulty at your band.", "",
    `## Existing ${band.name} episodes (counted and excluded: do not repeat their objective, example set or story)`, "");
  out.push(ex.length ? ex.map((e) => `- ${e.id} ${e.title}${e.skills.length ? ` (${e.skills.join(", ")})` : ""}`).join("\n") : "- None yet.");
  out.push("", "## Your slots and standards", "", bandTables(p, b), common);
  return `${out.join("\n")}\n`;
}
