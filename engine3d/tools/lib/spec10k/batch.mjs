// Batches for the spec writers: reserve the next free slots of a band, write a compact brief (the rows involved,
// the siblings already written, the band header), and keep the rolling state in 10K/progress.json so a run can
// resume after a stop. Spec files on disk are the truth; progress.json only records batches handed out.
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { BANDS, fmtSlot, parseSlots } from "./load.mjs";

/** @param {string} root */
export function readProgress(root) {
  const f = join(root, "progress.json");
  return existsSync(f) ? JSON.parse(readFileSync(f, "utf8")) : { description: "Batches handed to spec writers (spec10k next). Spec files are the truth; open batches are closed by the next `next` for the band.", batches: [] };
}

/**
 * The next `size` free slots of a band in row order (a slot is free when no spec file exists for it).
 * @param {object} p  programme
 * @param {string} b  band
 * @param {Set<string>} written  ids with a spec file
 * @param {number} size
 * @returns {{ id: string, row: object }[]}
 */
export function nextSlots(p, b, written, size) {
  const out = [];
  for (const row of p.allocation[b].rows ?? []) {
    const r = parseSlots(row.slots);
    if (!r) continue;
    for (let n = r[0]; n <= r[1] && out.length < size; n++) {
      const id = `${b}${fmtSlot(n)}`;
      if (!written.has(id)) out.push({ id, row });
    }
    if (out.length >= size) break;
  }
  return out;
}

const esc = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");

/**
 * Markdown brief for one batch.
 * @param {object} p
 * @param {string} b
 * @param {{ id: string, row: object }[]} slots
 * @param {object[]} specs  all parsed specs (for siblings)
 * @param {string} batchId
 */
export function batchBriefMd(p, b, slots, specs, batchId) {
  const band = p.bands.bands[b];
  const rows = [...new Set(slots.map((s) => s.row))];
  const out = [`# Batch ${batchId}: ${slots.length} ${b} specs (${band.name}, ages ${band.ages})`, "",
    "<!-- Generated by engine3d/tools/spec10k.mjs next. -->", "",
    `Write exactly these ids, one file each in \`10K/specs/${b}/<id>.json\`: ${slots.map((s) => s.id).join(", ")}.`, "",
    `Band: audience \`${band.audience}\`; length ${band.lengthS[0]}-${band.lengthS[1]} s; host ${band.host}; sidekick ${band.sidekick}; voice ${band.voice}; music ${band.music}; framework ${band.framework}.`, "",
    "## Rows in this batch", ""];
  for (const row of rows) {
    const mine = slots.filter((s) => s.row === row).map((s) => s.id);
    const r = parseSlots(row.slots);
    const sib = specs.filter((s) => { const n = Number(s.id.slice(2)); return s.band === b && n >= r[0] && n <= r[1]; }).sort((x, y) => (x.id < y.id ? -1 : 1));
    out.push(`### ${row.key} (slots ${row.slots}, ${row.count} videos; this batch: ${mine.join(", ")})`, "",
      `- Subject \`${row.subject}\`, strand \`${row.strand}\`, standards ${row.standards.map((c) => `\`${c}\``).join(", ")} (primary first).`,
      `- Standard: ${row.text}`,
      `- Series: ${(row.series ?? []).join(", ") || "any series of the band that fits"}.`,
      `- Variants to climb (simple → complex): ${(row.variants ?? []).join("; ")}.`);
    if (row.existing?.length) out.push(`- Existing episodes on this standard (do not repeat): ${row.existing.join(", ")}.`);
    if (row.notes) out.push(`- Notes: ${row.notes}`);
    if (row.skills?.length) out.push(`- Skills: ${row.skills.join(", ")}.`);
    out.push("");
    if (sib.length) {
      out.push(`Already written in this row (${sib.length}/${row.count}); yours must differ from all of them:`, "", "| Id | Title | Sub-skill | Example set | Diff | Magic |", "|---|---|---|---|---|---|");
      for (const s of sib) out.push(`| ${s.id} | ${esc(s.title)} | ${esc(s.distinct_by?.sub_skill)} | ${esc(s.distinct_by?.example_set)} | ${s.distinct_by?.difficulty} | ${s.magical_moment?.id} |`);
      out.push("");
    } else out.push("Nothing written in this row yet.", "");
  }
  out.push("Plan the whole row's ladder first (all its videos, simple → complex), then write your slots at their place on it, so later batches can continue the ladder.", "");
  return out.join("\n");
}

/**
 * STATUS.md: specs per band and the most-needed new assets/features.
 * @param {object} p
 * @param {object} cov  coverage()
 * @param {object} needs  aggregateNeeds()
 * @param {{ invalid: number, dups: number, when: string }} checks
 */
export function statusMd(p, cov, needs, checks) {
  const out = ["# 10K status", "", `Updated ${checks.when}. ${cov.written} / ${cov.target} specs (${Math.round((1000 * cov.written) / cov.target) / 10}%). Validate errors: ${checks.invalid}. Duplicate pairs / re-skins: ${checks.dups}.`, "",
    "| Band | Done | Target |", "|---|---|---|"];
  for (const b of BANDS) out.push(`| ${b} ${p.bands.bands[b].name} | ${cov.bands[b].written} | ${cov.bands[b].target} |`);
  for (const g of Object.keys(needs.new)) {
    const top = needs.new[g].slice(0, 15);
    out.push("", `## Top new ${g}`, "", top.length ? top.map((x) => `- \`${x.name}\` (${x.count}): ${esc(x.descriptions[0] ?? "")}`).join("\n") : "None.");
  }
  return `${out.join("\n")}\n`;
}
