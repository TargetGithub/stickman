// The Toy Box Friends episode list (scripts/series/toybox/EPISODES.md), built from three sources so it can't
// drift: the scripts themselves (id, title, audience, skills), the registry episodes.json (subject, status,
// render location, compilations, planned specs and topic ideas) and the education skills map (the gaps).
// tools/episodes.mjs writes or checks the file; tests/unit/episodes.test.js fails when it is stale.

import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";

export const STATUSES = ["spec", "scripted", "rendered", "uploaded"];
export const GRADES = ["babies", "prek", "k", "grade1", "grade2", "grade3", "grade4", "grade5"];
const GRADE_NAME = { babies: "Babies", prek: "Pre-K", k: "K", grade1: "Grade 1", grade2: "Grade 2", grade3: "Grade 3", grade4: "Grade 4", grade5: "Grade 5" };
// skills.json grades → script audiences.
const SKILL_GRADE = { prek: "prek", k: "k", 1: "grade1", 2: "grade2", 3: "grade3", 4: "grade4", 5: "grade5" };

/** Episode scripts in a series folder: { id, file, title, audience, skills } sorted by file name. */
export function readScripts(dir) {
  return readdirSync(dir).filter((f) => /^[a-z]+\d+_.*\.json$/.test(f) && f !== "episodes.json").sort().map((file) => {
    const s = JSON.parse(readFileSync(join(dir, file), "utf8"));
    const m = s.meta ?? {};
    return { id: m.episode ?? file.slice(0, 4), file, title: m.title ?? "", ytTitle: m.youtube?.title ?? "", audience: m.audience ?? "", skills: m.skills ?? [] };
  });
}

/**
 * Check the registry against the scripts. Returns a list of problems (empty when all is well).
 * @param {object} reg  episodes.json
 * @param {ReturnType<typeof readScripts>} scripts
 * @param {Record<string, object>} skills  skills.json skills
 */
export function checkRegistry(reg, scripts, skills) {
  const out = [];
  const ids = new Set(scripts.map((s) => s.id));
  for (const s of scripts) {
    const e = reg.episodes?.[s.id];
    if (!e) { out.push(`${s.id}: script ${s.file} has no entry in episodes.json`); continue; }
    if (!STATUSES.includes(e.status) || e.status === "spec") out.push(`${s.id}: a script exists, so status must be scripted, rendered or uploaded (is ${e.status})`);
    if ((e.status === "rendered" || e.status === "uploaded") && !e.render) out.push(`${s.id}: status ${e.status} needs a render location`);
    if (!e.subject) out.push(`${s.id}: no subject`);
    for (const k of s.skills) if (!skills[k]) out.push(`${s.id}: unknown skill ${k}`);
  }
  for (const [id, e] of Object.entries(reg.episodes ?? {})) {
    if (ids.has(id)) continue;
    if (e.status !== "spec") out.push(`${id}: status ${e.status} but no script file`);
    if (!e.title || !e.audience || !e.spec) out.push(`${id}: a planned episode needs title, audience and spec`);
    if (e.audience && !GRADES.includes(e.audience)) out.push(`${id}: unknown audience ${e.audience}`);
    for (const k of e.skills ?? []) if (!skills[k]) out.push(`${id}: unknown skill ${k}`);
  }
  return out;
}

const cell = (s) => String(s ?? "").replace(/\|/g, "\\|");

/**
 * The whole EPISODES.md text.
 * @param {{ reg:object, scripts:ReturnType<typeof readScripts>, skills:Record<string, object> }} o
 */
export function buildEpisodesMd({ reg, scripts, skills }) {
  const byId = new Map(scripts.map((s) => [s.id, s]));
  const rows = [];
  for (const s of scripts) rows.push({ ...reg.episodes?.[s.id], ...s, path: s.file });
  for (const [id, e] of Object.entries(reg.episodes ?? {})) if (!byId.has(id)) rows.push({ id, ...e, path: "–" });
  const order = (r) => GRADES.indexOf(r.audience) * 1000 + Number(r.id.replace(/\D/g, ""));
  rows.sort((a, b) => order(a) - order(b) || a.id.localeCompare(b.id));

  const count = (st) => rows.filter((r) => r.status === st).length;
  const L = [];
  L.push("# Toy Box Friends: every episode");
  L.push("");
  L.push("<!-- Generated by `node engine3d/tools/episodes.mjs` from the scripts in this folder, `episodes.json` and");
  L.push("     `catalog/education/skills.json`. Do not edit by hand: change episodes.json (status, render, subject, planned");
  L.push("     specs, ideas) or the scripts, then run the tool. `cd engine3d && npm test` fails when this file is stale. -->");
  L.push("");
  L.push(`${rows.length} episodes: ${STATUSES.map((s) => `${count(s)} ${s}`).join(", ")}. Status moves spec → scripted → rendered → uploaded.`);
  L.push("");
  L.push("Render locations: " + Object.entries(reg.roots ?? {}).map(([k, v]) => `\`${k}:\` = \`${v}\``).join("; ") + ".");
  L.push("");
  L.push("Update a status: `node engine3d/tools/episodes.mjs --set <id> <status> [location]`; find renders on disk: `--scan`.");
  for (const g of GRADES) {
    const list = rows.filter((r) => r.audience === g);
    if (!list.length) continue;
    L.push("");
    L.push(`## ${GRADE_NAME[g]} (${list.length})`);
    L.push("");
    L.push("| ID | Title | Grade | Subject | Skills | Script | Status | Render location |");
    L.push("|---|---|---|---|---|---|---|---|");
    for (const r of list) {
      L.push(`| ${r.id} | ${cell(r.title)} | ${GRADE_NAME[r.audience] ?? r.audience} | ${cell(r.subject)} | ${(r.skills ?? []).map((k) => `\`${k}\``).join(", ") || "–"} | ${r.path === "–" ? (r.spec ? `spec: ${cell(r.spec)}` : "–") : `\`${r.path}\``} | ${r.status} | ${cell(r.render) || "–"} |`);
    }
  }
  if (reg.compilations?.length) {
    L.push("");
    L.push("## Compilations");
    L.push("");
    L.push("| Name | Title | Episodes | Status | Render location |");
    L.push("|---|---|---|---|---|");
    for (const c of reg.compilations) L.push(`| ${c.name} | ${cell(c.title)} | ${c.episodes.join(", ")} | ${c.status} | ${cell(c.render) || "–"} |`);
  }

  // Gaps: skills of each grade that no episode (script or spec) teaches yet, plus topic ideas from the registry.
  const used = new Set(rows.flatMap((r) => r.skills ?? []));
  L.push("");
  L.push("## Planned / gaps");
  L.push("");
  L.push("Skills in `catalog/education/skills.json` that no episode above covers yet (computed), and topic ideas");
  L.push("for the next batches (`ideas` in episodes.json). Pick the next episodes from here.");
  for (const g of GRADES) {
    const free = Object.entries(skills).filter(([, v]) => SKILL_GRADE[v.grade] === g).map(([k]) => k).filter((k) => !used.has(k));
    const ideas = reg.ideas?.[g] ?? [];
    if (!free.length && !ideas.length) continue;
    L.push("");
    L.push(`### ${GRADE_NAME[g]}`);
    L.push("");
    if (free.length) L.push(`- Skills not covered: ${free.map((k) => `\`${k}\` (${skills[k].description.replace(/\.$/, "")})`).join("; ")}.`);
    for (const i of ideas) L.push(`- ${i}`);
  }
  L.push("");
  return L.join("\n");
}

/**
 * Find finished renders: folders named <id>_* holding final_4k60.mp4 under each root (two levels deep, so
 * playlist folders on the backup disk are searched). Returns id → "<root>:<relative path>".
 */
export function scanRenders(roots, ids) {
  const found = {};
  const walk = (rootName, base, rel, depth) => {
    let names;
    try { names = readdirSync(join(base, rel)); } catch { return; }
    for (const n of names) {
      const p = join(base, rel, n);
      let st; try { st = statSync(p); } catch { continue; }
      if (!st.isDirectory()) continue;
      const id = ids.find((i) => n.startsWith(`${i}_`));
      if (id && existsSync(join(p, "final_4k60.mp4"))) found[id] ??= `${rootName}:${join(rel, n)}`;
      else if (depth > 0) walk(rootName, base, join(rel, n), depth - 1);
    }
  };
  for (const [name, base] of Object.entries(roots)) walk(name, base, "", 2);
  return found;
}
